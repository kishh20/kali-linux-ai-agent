import json
import time
from typing import Dict, Any, List
from pathlib import Path
from app.config import HISTORY_FILE

def load_history() -> List[Dict[str, Any]]:
    if not HISTORY_FILE.exists():
        return []
    try:
        with open(HISTORY_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as e:
        print(f"[LabRecord] Error loading history: {e}")
        return []

def save_history_entry(entry: Dict[str, Any]) -> List[Dict[str, Any]]:
    history = load_history()
    # Add new entry to the front
    history.insert(0, entry)
    # Keep last 100 runs
    if len(history) > 100:
        history = history[:100]
    try:
        with open(HISTORY_FILE, "w", encoding="utf-8") as f:
            json.dump(history, f, indent=2)
    except Exception as e:
        print(f"[LabRecord] Error saving history: {e}")
    return history

def generate_markdown_record(data: Dict[str, Any]) -> str:
    """Generate official academic Linux Lab Record in Markdown."""
    title = data.get("title", "Linux Practical")
    number = data.get("number", "1")
    aim = data.get("aim", "Practical Aim")
    algorithm = data.get("algorithm", [])
    commands = data.get("commands", [])
    output = data.get("output", "")
    status = data.get("status", "UNKNOWN")
    timestamp = data.get("timestamp", time.strftime("%Y-%m-%d %H:%M:%S"))
    explanation = data.get("explanation", "")
    error = data.get("error", None)

    algo_text = "\n".join([f"{step}" for step in algorithm]) if isinstance(algorithm, list) else str(algorithm)
    cmds_text = "\n".join(commands) if isinstance(commands, list) else str(commands)

    record_md = f"""# PRACTICAL RECORD: EXPERIMENT {number}
## {title}

**Date of Execution:** {timestamp}  
**Execution Status:** {"[SUCCESS] PASSED" if status == "SUCCESS" else "[FAILED] INCOMPLETE"}  
**Operating System:** Kali Linux (Debian GNU/Linux)

---

### 1. AIM
{aim}

---

### 2. ALGORITHM
```text
{algo_text}
```

---

### 3. COMMANDS EXECUTED
```bash
{cmds_text}
```

---

### 4. ACTUAL TERMINAL OUTPUT
```text
{output.strip() if output else "[No terminal output captured]"}
```

---

### 5. TECHNICAL ANALYSIS & COMMAND EXPLANATION
{explanation}

{f"**Error Encountered:** {error}" if error else ""}

---

### 6. RESULT
The practical experiment **'{title}'** was executed {"successfully without errors on Kali Linux." if status == "SUCCESS" else "with errors encountered during execution. See terminal log for diagnostic details."} All specified system administrative tasks and verifications were evaluated against the live Kali shell environment.

---
*Generated by Kali Linux AI Practical Automation Agent*
"""
    return record_md

